class PublicationError(ValueError):
    pass


def require(condition):
    if not condition:
        raise PublicationError('unverified public producer field')


def project(raw, bindings, producer, scanner):
    text = raw.decode('utf-8', 'strict')
    json.loads(text, object_pairs_hook=_trivy_report.unique, parse_constant=_trivy_report.nonfinite)
    changes = []
    seen = set()
    for path, value, start, end in producer.string_spans(text):
        if path in bindings:
            expected, allowed_rules = bindings[path]
            require(expected == value and path not in seen)
            # Public provenance permits only the known metadata false-positive
            # classes. Secret, encoding and every other rule still inspect
            # the original recognized scalar, even if its source is public.
            findings = []
            for representation in (text[start:end].encode(), value.encode('utf-8', 'strict')):
                findings.extend(scanner.scan_generated_bytes(representation, 'qualification-evidence/public-field.json', False, []))
            require(not any(item.rule not in allowed_rules for item in findings))
            seen.add(path)
            # This internal view is never published. Fixed short words avoid
            # introducing another opaque digest into the encoding detector;
            # stage receipts bind the complete original and view bytes.
            changes.append((start, end, json.dumps('[verified public field]')))
    require(seen == set(bindings))
    pieces, previous = [], 0
    for start, end, replacement in changes:
        pieces.extend((text[previous:start], replacement))
        previous = end
    return ''.join([*pieces, text[previous:]]).encode()


def go_citations(document, metadata):
    prefix = ':'.join(('file', '//$GOPATH/pkg/mod/'))
    known = {prefix + row['module'] + '@' + row['version'] + '/' + row['file']: row for row in metadata['licenses']}
    bindings = {}
    for index, record in enumerate(document.get('hasExtractedLicensingInfos', [])):
        require(isinstance(record, dict) and isinstance(record.get('seeAlsos', []), list))
        for position, value in enumerate(record.get('seeAlsos', [])):
            if isinstance(value, str) and value in known:
                body = known[value]['content'].decode().strip()
                text = record.get('extractedText', 'NOASSERTION')
                require(isinstance(text, str) and (text in ('', 'NOASSERTION') or body in text))
                bindings[('hasExtractedLicensingInfos', index, 'seeAlsos', position)] = value, frozenset({'PATH001'})
    return bindings


def syft_view(raw, metadata, producer, scanner):
    document = json.loads(raw, object_pairs_hook=_trivy_report.unique)
    require(document.get('spdxVersion') == 'SPDX-2.3' and 'Tool: syft-1.50.0' in document.get('creationInfo', {}).get('creators', []))
    namespace = document.get('documentNamespace')
    require(isinstance(namespace, str))
    # Only the suffix generated by uuid.NewRandom is projected. Prefix/name
    # bytes remain available to every original privacy rule, including paths.
    nonce = re.search(r'(?<=-)[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$', namespace)
    require(nonce is not None and namespace.startswith(('https://anchore.com/syft/file/', 'https://anchore.com/syft/image/')))
    text = raw.decode('utf-8', 'strict')
    spans = [(start, end) for path, value, start, end in producer.string_spans(text) if path == ('documentNamespace',) and value == namespace]
    require(len(spans) == 1)
    start, end = spans[0]
    token = text[start:end]
    require(token.endswith(nonce[0] + '"'))
    text = text[:end - 37] + 'public-nonce' + text[end - 1:]
    return project(text.encode(), go_citations(document, metadata), producer, scanner)


def buildkit_view(raw, producer, scanner):
    document = json.loads(raw, object_pairs_hook=_trivy_report.unique)
    require(set(document) == {'stdout', 'pid'} and isinstance(document['stdout'], str) and type(document['pid']) is int)
    lines = document['stdout'].splitlines(keepends=True)
    in_policy, replaced = False, 0
    atom_sha256 = '56bcacfa79639bf7dd99324b1857327f5910663709618010021a9855370ea728'
    for index, line in enumerate(lines):
        if re.fullmatch(r'GC Policy rule#[0-9]+:\r?\n', line):
            in_policy = True
        elif line and not line[0].isspace():
            in_policy = False
        if in_policy and line.startswith('Filters:'):
            # buildctl uses tabwriter, so Filters is indented with a tab in
            # the native format; the branch below handles that exact form.
            raise PublicationError('unknown verbose GC filter indentation')
        if in_policy and re.match(r'^\tFilters:\s+', line):
            pieces = re.split(r'(,|\s+)', line)
            for position, piece in enumerate(pieces):
                if piece.startswith('type==') and hashlib.sha256(piece.encode()).hexdigest() == atom_sha256:
                    pieces[position] = 'public-gc-source-enum'
                    replaced += 1
            lines[index] = ''.join(pieces)
    require(replaced > 0)
    # Only the known atom is changed; all surrounding stdout still scans.
    stdout = ''.join(lines)
    require(not scanner.scan_generated_bytes(stdout.encode(), 'qualification-evidence/buildkit-stdout.txt', False, []))
    text = raw.decode('utf-8', 'strict')
    spans = [(start, end) for path, value, start, end in producer.string_spans(text) if path == ('stdout',) and value == document['stdout']]
    require(len(spans) == 1)
    start, end = spans[0]
    # The controlled wrapper is Python's canonical string encoder. Refuse
    # another lexical representation rather than rewriting unrelated bytes.
    require(text[start:end] == json.dumps(document['stdout']))
    return (text[:start] + json.dumps(stdout) + text[end:]).encode()


def package_identity(package, os_name):
    purl = package.get('Identifier', {}).get('PURL')
    require(isinstance(purl, str))
    url = urllib.parse.urlsplit(purl)
    require(url.scheme == 'pkg' and not url.netloc and not url.fragment)
    path = urllib.parse.unquote(url.path)
    prefix = 'deb/debian/' + package['Name'] + '@'
    require(path.startswith(prefix))
    version = path[len(prefix):]
    query = urllib.parse.parse_qs(url.query, keep_blank_values=True, strict_parsing=True)
    require(set(query) <= {'arch', 'distro', 'epoch'} and all(len(value) == 1 for value in query.values()))
    epoch = query.get('epoch', ['0'])[0]
    native_version = package['Version'] + ('-' + package['Release'] if package.get('Release') else '')
    require(epoch.isdigit() and str(package.get('Epoch', 0)) == epoch and version == native_version)
    require(query.get('arch') == [package['Arch']] and query.get('distro') == ['debian-' + os_name])
    return package['Name'], (epoch + ':' if epoch != '0' else '') + version, package['Arch']


def archive_names(raw, expected_identity):
    require(raw[:8] == b'!<arch>\n' and len(raw) <= 2**20)
    position, members = 8, {}
    while position < len(raw):
        require(position + 60 <= len(raw))
        header = raw[position:position + 60]
        require(header[-2:] == b'`\n')
        name = header[:16].decode('ascii').strip().rstrip('/')
        size = int(header[48:58].decode('ascii').strip())
        require(name not in members and 0 <= size <= len(raw) - position - 60)
        members[name] = raw[position + 60:position + 60 + size]
        position += 60 + size + size % 2
    require(position == len(raw) and members.pop('debian-binary', None) == b'2.0\n')
    controls = [name for name in members if name.startswith('control.tar.')]
    payloads = [name for name in members if name.startswith('data.tar.')]
    require(len(controls) == len(payloads) == 1 and len(members) == 2)
    with tarfile.open(fileobj=io.BytesIO(members[controls[0]]), mode='r:*') as archive:
        entries = archive.getmembers()
        require(len(entries) < 100 and sum(m.size for m in entries) < 2**20)
        control = [m for m in entries if m.name.removeprefix('./') == 'control']
        require(len(control) == 1 and control[0].isfile())
        fields = dict(line.split(': ', 1) for line in archive.extractfile(control[0]).read().decode().splitlines() if line and not line[0].isspace())
        require(tuple(fields[key] for key in ('Package', 'Version', 'Architecture')) == expected_identity)
    names = set()
    with tarfile.open(fileobj=io.BytesIO(members[payloads[0]]), mode='r:*') as archive:
        entries = archive.getmembers()
        require(len(entries) < 4096 and sum(m.size for m in entries) < 16 * 2**20)
        for member in entries:
            name = member.name.removeprefix('./').rstrip('/')
            require(name not in names and '\\' not in name and (all(p not in ('..', '') for p in name.split('/')) if name else member.isdir()))
            names.add(name)
    return names


class Stage:
    def __init__(self, root, role, scanner, producer, *, metadata=None, upstream=()):
        require(role in ('buildkit', 'scan'))
        self.root, self.role, self.scanner, self.producer = root, role, scanner, producer
        self.metadata, self.upstream = metadata, upstream
        self.allowlist = scanner.load_allowlist(root / 'source' / scanner.ALLOWLIST_FILENAME)
        self.directory = root / ('staged-' + role)
        self.directory.mkdir(mode=0o700)
        self.rows = []
        self.packages = {}
        self.archives = {}
        if metadata is not None:
            require(not list(self.allowlist.filter(scanner.scan_bytes_as_file(metadata['source_raw'], metadata['source_path'], fixture=False))))

    def signed_packages(self, packages, os_name):
        identities = {package_identity(package, os_name) for package in packages}
        missing = identities - self.packages.keys()
        if missing:
            registry = json.loads(self.producer.committed(self.root / 'source', self.producer.REGISTRY))
            candidates = {}
            for row in registry['debian_indexes']:
                found = self.producer.verified_index(row, self.root / 'debian-cache', missing)
                for identity, (fields, stanza) in found.items():
                    candidates.setdefault(identity, []).append((row, fields, stanza))
            for identity in missing:
                rows = candidates.get(identity, [])
                require(bool(rows) and len({(fields['SHA256'], fields.get('Maintainer'), fields.get('Source')) for _row, fields, _stanza in rows}) == 1)
                self.packages[identity] = rows[0]

    def public_archive_names(self, identity):
        if identity not in self.archives:
            row, fields, _stanza = self.packages[identity]
            filename = fields['Filename']
            require(identity == ('adduser', '3.134', 'all') and filename.startswith('pool/main/a/adduser/'))
            url = row['url'].split('/dists/', 1)[0] + '/' + filename
            relative = urllib.parse.urlsplit(url).path.removeprefix('/')
            cache = self.root / 'debian-cache'
            stored = self.root / 'public-package-inputs' / (fields['SHA256'] + '.deb')
            if (cache / relative).exists():
                raw = self.producer.cached_bytes(cache, relative, 2**20)
            elif stored.exists():
                raw = _trivy_report.stable_bytes(stored, 2**20)
            else:
                raw = self.producer.debian_bytes(url, 2**20, None, fields['SHA256'])
                require(len(raw) == int(fields['Size']) and hashlib.sha256(raw).hexdigest() == fields['SHA256'])
                stored.parent.mkdir(mode=0o700, exist_ok=True)
                with stored.open('xb') as stream:
                    stream.write(raw)
            require(len(raw) == int(fields['Size']) and hashlib.sha256(raw).hexdigest() == fields['SHA256'])
            self.archives[identity] = archive_names(raw, identity)
        return self.archives[identity]

    def trivy_view(self, raw, database, git_identity, rendering):
        document = json.loads(raw, object_pairs_hook=_trivy_report.unique)
        require(document.get('SchemaVersion') == 2 and document.get('Trivy') == {'Version': '0.72.0'})
        metadata = document.get('Metadata', {})
        require(rendering.get('method') == _trivy_report.METHOD and rendering.get('rendered_sha256') == hashlib.sha256(raw).hexdigest() and re.fullmatch('sha256:[0-9a-f]{64}', document.get('ReportID', '')) is not None)
        digest_rules = frozenset({'MAIL001', 'HOST001', 'IP001', 'PATH001', 'DEPLOYID002'})
        bindings = {('ReportID',): (document['ReportID'], digest_rules)}
        # Pinned Trivy pkg/fingerprint/fingerprint.go computes this exact
        # digest from four still-scanned report fields. Pattern alone never
        # authenticates an encoded value in a finding or unknown field.
        for index, result in enumerate(document.get('Results', [])):
            for position, finding in enumerate(result.get('Vulnerabilities', [])):
                parts = (document.get('ArtifactID', ''), result.get('Target'), finding.get('PkgID', ''), finding.get('VulnerabilityID'))
                require(all(isinstance(part, str) and len(part.encode()) <= 4096 for part in parts))
                expected = 'sha256:' + hashlib.sha256(':'.join(parts).encode()).hexdigest()
                require(finding.get('Fingerprint') == expected)
                bindings[('Results', index, 'Vulnerabilities', position, 'Fingerprint')] = expected, digest_rules
        if 'Commit' in metadata:
            require(metadata.get('Commit') == git_identity['Commit'] and metadata.get('RepoURL') == git_identity['RepoURL'])
            # Hosting provenance is the exact admitted public repository,
            # which can differ from the project's canonical module identity.
            # Other occurrences and near-misses retain the identity rule.
            bindings[('Metadata', 'RepoURL')] = metadata['RepoURL'], frozenset({'REPO_IDENTITY'})
            for field in ('Author', 'Committer'):
                require(metadata.get(field) == git_identity[field])
                bindings[('Metadata', field)] = metadata[field], frozenset({'MAIL001'})
        os_record = metadata.get('OS', {})
        os_name = os_record.get('Name', '')
        for index, result in enumerate(document.get('Results', [])):
            if result.get('Type') != 'debian':
                continue
            require(os_record.get('Family') == 'debian' and re.fullmatch(r'12(?:\.[0-9]+)?', os_name) is not None)
            packages = result.get('Packages', [])
            require(isinstance(packages, list) and len(packages) <= 2048)
            self.signed_packages(packages, os_name)
            by_id = {}
            for position, package in enumerate(packages):
                identity = package_identity(package, os_name)
                _row, fields, _stanza = self.packages[identity]
                require(package['ID'] not in by_id)
                source = re.fullmatch(r'([A-Za-z0-9+.-]+)(?: \(([^()]+)\))?', fields.get('Source', fields['Package']))
                require(source is not None and package.get('SrcName') == source[1])
                source_version = package.get('SrcVersion', '') + ('-' + package['SrcRelease'] if package.get('SrcRelease') else '')
                if package.get('SrcEpoch', 0):
                    source_version = str(package['SrcEpoch']) + ':' + source_version
                require(source_version == (source[2] or fields['Version']))
                by_id[package['ID']] = package, identity, source[1]
                base = ('Results', index, 'Packages', position)
                if package.get('Maintainer') == fields.get('Maintainer'):
                    bindings[(*base, 'Maintainer')] = package['Maintainer'], frozenset({'MAIL001'})
                bindings[(*base, 'Identifier', 'PURL')] = package['Identifier']['PURL'], frozenset({'MAIL001'})
                if identity == ('adduser', '3.134', 'all'):
                    for number, name in enumerate(package.get('InstalledFiles', [])):
                        if isinstance(name, str) and name.removeprefix('/') in self.public_archive_names(identity):
                            bindings[(*base, 'InstalledFiles', number)] = name, frozenset({'HOST001'})
            for position, vulnerability in enumerate(result.get('Vulnerabilities', [])):
                package_record = by_id.get(vulnerability.get('PkgID'))
                if package_record is None:
                    continue
                package, identity, source_name = package_record
                base = ('Results', index, 'Vulnerabilities', position)
                purl = vulnerability.get('PkgIdentifier', {}).get('PURL')
                if purl == package['Identifier']['PURL'] and vulnerability.get('PkgName') == package['Name']:
                    bindings[(*base, 'PkgIdentifier', 'PURL')] = purl, frozenset({'MAIL001'})
                identifier = vulnerability.get('VulnerabilityID', '')
                if (re.fullmatch(r'CVE-[0-9]{4}-[0-9]{4,}', identifier) is None
                        or vulnerability.get('DataSource', {}).get('ID') != 'debian'
                        or vulnerability.get('PkgName') != package['Name']
                        or vulnerability.get('InstalledVersion') != identity[1]):
                    continue
                advisory = database.value([b'debian 12', source_name.encode()], identifier.encode())
                record = database.value([b'vulnerability'], identifier.encode())
                if advisory is None or record is None:
                    continue
                json.loads(advisory, object_pairs_hook=_trivy_report.unique)
                public = json.loads(record, object_pairs_hook=_trivy_report.unique)
                for field in ('Title', 'Description'):
                    value = vulnerability.get(field)
                    if isinstance(value, str) and value == public.get(field):
                        bindings[(*base, field)] = value, frozenset({'MAIL001', 'HOST001', 'IP001', 'PATH001', 'DEPLOYID002'})
                references = public.get('References', [])
                for number, value in enumerate(vulnerability.get('References', [])):
                    if isinstance(value, str) and number < len(references) and value == references[number]:
                        bindings[(*base, 'References', number)] = value, frozenset({'MAIL001', 'HOST001', 'IP001', 'PATH001', 'DEPLOYID002'})
        return project(raw, bindings, self.producer, self.scanner)

    def add(self, path, original, view):
        relative = path.relative_to(self.root / 'evidence').as_posix()
        require(relative not in {row['path'] for row in self.rows})
        findings = self.scanner.scan_generated_bytes(view, 'qualification-evidence/' + relative, False, self.upstream, public_metadata=self.metadata)
        require(not list(self.allowlist.filter(findings)))
        require(_trivy_report.stable_bytes(path, _trivy_report.LIMIT) == original)
        target = self.directory / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(original)
        self.rows.append({'path': relative, 'bytes': len(original), 'sha256': hashlib.sha256(original).hexdigest(), 'view_sha256': hashlib.sha256(view).hexdigest()})

    def finish(self):
        inputs = json.loads((self.root / 'inputs.json').read_text())
        raw = (json.dumps({'schema_version': 1, 'role': self.role, 'source_commit': inputs['commit'], 'source_tree': inputs['tree'], 'files': self.rows}, indent=2) + '\n').encode()
        with (self.directory / 'manifest.json').open('xb') as stream:
            stream.write(raw)


class StageAdmission:
    """In-memory transfer from the controller after both actual workers joined."""
    def __init__(self, root, files, manifests):
        self.root, self.files, self.manifests = root, files, manifests


def completed_stages(root):
    # Called only by the controller's successful two-worker path. These
    # manifests transport already checked bytes from those workers; a report,
    # CLI argument or standalone sidecar cannot request field recognition.
    import _bounded_qualification as q
    inputs = json.loads((root / 'inputs.json').read_text())
    runtime = json.loads((root / 'source/release/manifest.json').read_text())['runtime']
    images = {row['name'] for row in runtime['images']}
    expected = {'buildkit': {'buildkit-workers-apt-plan.json'} | {'buildkit-workers-' + letter + '-' + name + '.json' for letter in ('A', 'B') for name in images}, 'scan': {'security-source.json', 'security-binaries-A.json', 'security-binaries-B.json', 'runner-all-severities.json'} | {'security-image-' + name + '.json' for name in images} | {'sbom/' + name + '.raw.spdx.json' for name in images | {row['name'] for row in runtime['binaries']}}}
    files, manifests = {}, []
    for role, members in expected.items():
        directory = root / ('staged-' + role)
        manifest = json.loads(_trivy_report.stable_bytes(directory / 'manifest.json', 2**20), object_pairs_hook=_trivy_report.unique)
        require(set(manifest) == {'schema_version', 'role', 'source_commit', 'source_tree', 'files'} and manifest['schema_version'] == 1 and manifest['role'] == role and manifest['source_commit'] == inputs['commit'] and manifest['source_tree'] == inputs['tree'])
        rows = manifest['files']
        require(isinstance(rows, list) and len(rows) == len(members) and {row['path'] for row in rows} == members)
        actual = q.inventory(directory)
        require({row['path'] for row in actual} == members | {'manifest.json'})
        indexed = {row['path']: row for row in actual}
        for row in rows:
            require(set(row) == {'path', 'bytes', 'sha256', 'view_sha256'} and type(row['bytes']) is int and row['bytes'] > 0 and re.fullmatch('[0-9a-f]{64}', row['sha256']) is not None and re.fullmatch('[0-9a-f]{64}', row['view_sha256']) is not None)
            require(indexed[row['path']] == {key: row[key] for key in ('path', 'bytes', 'sha256')} and row['path'] not in files)
            original = _trivy_report.stable_bytes(root / 'evidence' / row['path'], _trivy_report.LIMIT)
            require(len(original) == row['bytes'] and hashlib.sha256(original).hexdigest() == row['sha256'])
            files[row['path']] = row
        manifests.append(manifest)
    return StageAdmission(root, files, manifests)
